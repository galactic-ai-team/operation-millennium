# --- Population helpers (Section 3.4, 3.5) ------------------------------


def clause_count(n: int, a_hundredths: int) -> int:
    """Exact clause count ``m = (A*n + 50) // 100`` (Section 3.4)."""
    return (a_hundredths * n + 50) // 100


def _seed_from_material(material: str) -> int:
    """First 16 bytes of SHA-256(material), as an unsigned big-endian int."""
    digest = hashlib.sha256(material.encode("utf-8")).digest()
    return int.from_bytes(digest[:16], byteorder="big", signed=False)


def confirmatory_seed(n: int, a_hundredths: int, i: int) -> int:
    """Frozen confirmatory seed for cell ``(n, A)``, index ``i``.

    Seed material is UTF-8 ``"OM-C001-R2|n|A|i"`` with base-10 integers.
    This function is provided so the seed scheme can be tested and so
    Claude's runner and this analysis agree exactly. It must not be
    used to run confirmatory instances before Lumi authorises
    confirmatory execution (Section 3.5 / Section 8).
    """
    return _seed_from_material(f"{CONFIRMATORY_SEED_PREFIX}|{n}|{a_hundredths}|{i}")


def pilot_seed(n: int, a_hundredths: int, i: int) -> int:
    """Pilot seed. Same construction, different prefix, so pilot seeds
    can never collide with confirmatory seeds and pilot instances are
    a separate population."""
    return _seed_from_material(f"{PILOT_SEED_PREFIX}|{n}|{a_hundredths}|{i}")


def seed_manifest() -> list[dict]:
    """The full 2800-row confirmatory seed manifest (no runs attached).

    Indices 0..69 are training, 70..99 are test. Use this to check
    for seed collisions and to confirm the population shape; do not
    use it to execute confirmatory runs before authorisation.
    """
    manifest: list[dict] = []
    for n in N_VALUES:
        for a in A_VALUES:
            m = clause_count(n, a)
            for i in range(100):
                manifest.append(
                    {
                        "n": n,
                        "a_hundredths": a,
                        "m": m,
                        "index": i,
                        "split": "train" if i <= TRAIN_INDEX_MAX else "test",
                        "seed": confirmatory_seed(n, a, i),
                    }
                )
    return manifest


def check_seed_manifest(manifest: list[dict]) -> dict:
    """Collision / Phase-1-overlap checks for a seed manifest.

    Phase 1 experiments used small integer seeds (base 2026 scheme,
    all below PHASE1_SEED_MAX); confirmatory seeds are 128-bit
    SHA-256 outputs, so the two populations are disjoint by
    construction. This is checked, not assumed.
    """
    seeds = [row["seed"] for row in manifest]
    return {
        "n_rows": len(manifest),
        "n_distinct_seeds": len(set(seeds)),
        "has_collision": len(set(seeds)) != len(seeds),
        "min_seed": min(seeds) if seeds else None,
        "phase1_seeds_below_10m": all(s < PHASE1_SEED_MAX for s in seeds),
        "disjoint_from_phase1_scheme": all(s > PHASE1_SEED_MAX for s in seeds),
    }


# --- Row construction ----------------------------------------------------


def capped_log_effort(decisions: int, timed_out: bool, budget: int = BUDGET_B) -> float:
    """Primary response ``Y = ln(1 + min(D, B))`` (Section 3.7).

    Budget-exhausted runs receive ``ln(1 + B)``; completed runs use
    their recorded attempt count. The capped value never estimates
    effort beyond the cap.
    """
    if timed_out:
        return math.log1p(budget)
    return math.log1p(min(int(decisions), budget))


def status_from_solver(
    satisfiable: bool, timed_out: bool
) -> str:
    """SAT / UNSAT / UNKNOWN. UNKNOWN is never UNSAT (Section 4.2)."""
    if timed_out:
        return "UNKNOWN"
    return "SAT" if satisfiable else "UNSAT"


def make_row(
    *,
    n: int,
    m: int,
    a_hundredths: int | None,
    index: int | None,
    split: str,
    seed: int | None,
    width: int,
    degree_mean: float,
    decisions: int,
    timed_out: bool,
    satisfiable: bool,
    verified: bool,
    verification_status: str | None = None,
    width_reversed: int | None = None,
    budget: int = BUDGET_B,
) -> dict:
    """Build one analysis row from a solver run plus its features.

    ``verification_status`` follows Section 4.1 when supplied;
    otherwise it is derived honestly: SAT with a checked witness is
    ``SAT_WITNESS_CHECKED``; UNSAT without a proof certificate is
    ``UNVERIFIED`` -- no second solver ran, so there is no agreement
    to report (a lone DPLL UNSAT is not evidence; see
    REVIEW_PR10_NOVA.md NOVA-R10-13); UNKNOWN is ``NOT_APPLICABLE``
    (no satisfiability claim is made).
    """
    status = status_from_solver(satisfiable, timed_out)
    if verification_status is None:
        if status == "SAT":
            verification_status = (
                "SAT_WITNESS_CHECKED" if verified else "INVALID"
            )
        elif status == "UNSAT":
            verification_status = "UNVERIFIED"
        else:
            verification_status = "NOT_APPLICABLE"
    return {
        "n": int(n),
        "m": int(m),
        "a_hundredths": a_hundredths,
        "index": index,
        "split": split,
        "seed": seed,
        "width": int(width),
        "degree_mean": float(degree_mean),
        "decisions": int(decisions),
        "timed_out": bool(timed_out),
        "satisfiable": bool(satisfiable),
        "status": status,
        "verified": bool(verified),
        "verification_status": verification_status,
        "y": capped_log_effort(decisions, timed_out, budget=budget),
        "width_reversed": width_reversed,
    }


# --- Correlation helpers (stdlib; no test-set fitting) -------------------


def _pearson(xs: list[float], ys: list[float]) -> float | None:
    if len(xs) < 3 or len(xs) != len(ys):
        return None
    mx, my = statistics.fmean(xs), statistics.fmean(ys)
    den = math.sqrt(
        sum((x - mx) ** 2 for x in xs) * sum((y - my) ** 2 for y in ys)
    )
    if den == 0:
        return None
    return sum((x - mx) * (y - my) for x, y in zip(xs, ys)) / den


def _ranks(values: list[float]) -> list[float]:
    order = sorted(range(len(values)), key=lambda i: values[i])
    ranks = [0.0] * len(values)
    i = 0
    while i < len(order):
        j = i
        while j + 1 < len(order) and values[order[j + 1]] == values[order[i]]:
            j += 1
        avg = (i + j) / 2.0 + 1.0
        for k in range(i, j + 1):
            ranks[order[k]] = avg
        i = j + 1
    return ranks


def _spearman(xs: list[float], ys: list[float]) -> float | None:
    if len(xs) < 3:
        return None
    return _pearson(_ranks(xs), _ranks(ys))


# --- Primary models (Section 3.8, training rows only) --------------------


def _cell_key(row: dict) -> tuple[int, int]:
    return (int(row["n"]), int(row["m"]))


def _within_cell_centered_sums(
    train_rows: list[dict], *feature_names: str
) -> dict:
    """Pooled within-cell centred sums over training rows only.

    Returns, for each feature, ``Sff`` (sum of squared centred values)
    and ``Sfy`` (sum of centred feature * centred Y), plus the
    cross-feature sums ``Sfg`` for every feature pair, and the
    per-cell means. No test row is touched.
    """
    by_cell: dict[tuple[int, int], list[dict]] = defaultdict(list)
    for row in train_rows:
        by_cell[_cell_key(row)].append(row)
    cell_mean_y: dict[tuple[int, int], float] = {}
    cell_mean_f: dict[tuple[int, int], dict[str, float]] = {}
    for cell, rows in by_cell.items():
        cell_mean_y[cell] = statistics.fmean([r["y"] for r in rows])
        cell_mean_f[cell] = {
            name: statistics.fmean([float(r[name]) for r in rows])
            for name in feature_names
        }
    out: dict = {
        "cell_mean_y": cell_mean_y,
        "cell_mean_f": cell_mean_f,
        "n_train": len(train_rows),
    }
    for name in feature_names:
        out[f"S{name}{name}"] = 0.0
        out[f"S{name}y"] = 0.0
    for i, name in enumerate(feature_names):
        for other in feature_names[i + 1:]:
            out[f"S{name}{other}"] = 0.0
    for row in train_rows:
        cell = _cell_key(row)
        dy = row["y"] - cell_mean_y[cell]
        centred = {
            name: float(row[name]) - cell_mean_f[cell][name]
            for name in feature_names
        }
        for name in feature_names:
            out[f"S{name}{name}"] += centred[name] ** 2
            out[f"S{name}y"] += centred[name] * dy
        for i, name in enumerate(feature_names):
            for other in feature_names[i + 1:]:
                out[f"S{name}{other}"] += centred[name] * centred[other]
    return out


def fit_m0_m1(train_rows: list[dict]) -> dict:
    """Fit M0 and M1 on training rows only (Section 3.8).

    ``beta`` is None when the slope denominator is zero (width
    unidentifiable); the caller must then record INCONCLUSIVE, not
    substitute another proxy.
    """
    sums = _within_cell_centered_sums(train_rows, "width")
    denominator = sums["Swidthwidth"]
    beta = sums["Swidthy"] / denominator if denominator != 0 else None
    # Within-cell width variation is the identifying variation for M1;
    # report it so a near-zero denominator is visible, not silent.
    widths = [float(r["width"]) for r in train_rows]
    return {
        "cell_mean_y": sums["cell_mean_y"],
        "cell_mean_width": {
            cell: vals["width"] for cell, vals in sums["cell_mean_f"].items()
        },
        "beta": beta,
        "slope_denominator": denominator,
        "slope_numerator": sums["Swidthy"],
        "n_train": len(train_rows),
        "width_mean": statistics.fmean(widths) if widths else 0.0,
        "width_std": statistics.pstdev(widths) if len(widths) > 1 else 0.0,
    }


def fit_degree_adjusted(train_rows: list[dict]) -> dict:
    """Secondary models M2 / M3 (Section 3.11 item 3), training only.

    M2: cell effects + one shared slope on centred co-occurrence mean
    degree. M3: cell effects + joint least-squares slopes on centred
    degree and centred width (2x2 normal equations). A singular
    system is reported as such; it is not repaired by dropping a
    feature post hoc. M3 is treated as singular unless the relative
    determinant exceeds 1e-12 (rel_det = det / (sdd*sww) = 1 -
    (within-cell correlation)^2). That threshold is an
    implementation choice, not a prereg constant (it appears in no
    section of DISCOVERY_ROUND_01); it guards the 2x2 solve against
    near-collinear degree and width, whose slope estimates blow up
    as rel_det -> 0 (DEE-R9-03).
    """
    sums = _within_cell_centered_sums(train_rows, "degree_mean", "width")
    sdd = sums["Sdegree_meandegree_mean"]
    sww = sums["Swidthwidth"]
    sdw = sums["Sdegree_meanwidth"]
    sdy = sums["Sdegree_meany"]
    swy = sums["Swidthy"]
    beta_d_m2 = sdy / sdd if sdd != 0 else None
    det = sdd * sww - sdw * sdw
    # Relative determinant: 1 - (within-cell correlation)^2. Near zero
    # means degree and width are (near-)collinear within cells.
    rel_det = det / (sdd * sww) if sdd > 0 and sww > 0 else 0.0
    m3: dict = {"singular": True, "beta_degree": None, "beta_width": None}
    if det != 0 and rel_det > 1e-12:
        m3 = {
            "singular": False,
            "beta_degree": (sdy * sww - swy * sdw) / det,
            "beta_width": (swy * sdd - sdy * sdw) / det,
        }
    return {
        "cell_mean_y": sums["cell_mean_y"],
        "cell_mean_degree": {
            cell: vals["degree_mean"]
            for cell, vals in sums["cell_mean_f"].items()
        },
        "cell_mean_width": {
            cell: vals["width"] for cell, vals in sums["cell_mean_f"].items()
        },
        "m2_beta_degree": beta_d_m2,
        "m2_denominator": sdd,
        "m3": m3,
        "m3_determinant": det,
        "m3_relative_determinant": rel_det,
        "n_train": len(train_rows),
    }


def _clip(value: float, budget: int = BUDGET_B) -> float:
    return min(max(value, 0.0), math.log1p(budget))


def predict_m0(row: dict, fit: dict, budget: int = BUDGET_B) -> float:
    return _clip(fit["cell_mean_y"][_cell_key(row)], budget)


def predict_m1(row: dict, fit: dict, budget: int = BUDGET_B) -> float:
    if fit["beta"] is None:
        raise ValueError("M1 slope is unidentifiable (denominator zero)")
    cell = _cell_key(row)
    return _clip(
        fit["cell_mean_y"][cell]
        + fit["beta"] * (float(row["width"]) - fit["cell_mean_width"][cell]),
        budget,
    )


def predict_m2(row: dict, fit_deg: dict, budget: int = BUDGET_B) -> float:
    if fit_deg["m2_beta_degree"] is None:
        raise ValueError("M2 slope is unidentifiable (denominator zero)")
    cell = _cell_key(row)
    return _clip(
        fit_deg["cell_mean_y"][cell]
        + fit_deg["m2_beta_degree"]
        * (float(row["degree_mean"]) - fit_deg["cell_mean_degree"][cell]),
        budget,
    )


def predict_m3(row: dict, fit_deg: dict, budget: int = BUDGET_B) -> float:
    if fit_deg["m3"]["singular"]:
        raise ValueError("M3 joint slopes are singular")
    cell = _cell_key(row)
    return _clip(
        fit_deg["cell_mean_y"][cell]
        + fit_deg["m3"]["beta_degree"]
        * (float(row["degree_mean"]) - fit_deg["cell_mean_degree"][cell])
        + fit_deg["m3"]["beta_width"]
        * (float(row["width"]) - fit_deg["cell_mean_width"][cell]),
        budget,
    )


# --- Evaluation ------------------------------------------------------------


def evaluate(
    test_rows: list[dict],
    fit: dict,
    fit_deg: dict,
    budget: int = BUDGET_B,
) -> dict:
    """Held-out MAE for M0/M1/M2/M3 and per-cell summaries.

    Models are fixed inputs; this function fits nothing. M2/M3 are
    reported as None when their slopes are unidentifiable. Overall
    MAEs are equal-cell-weighted (Section 3.10: "Retain equal cell
    weights"): the mean of the per-cell MAEs, not the mean over all
    test rows (DEE-R9-17). For the frozen confirmatory population
    every test cell has exactly 30 rows, so the two coincide.
    """
    if not test_rows:
        raise ValueError("no test rows to evaluate")
    if fit["beta"] is None:
        raise ValueError("M1 slope is unidentifiable (denominator zero)")
    paired: list[dict] = []
    for row in test_rows:
        y = float(row["y"])
        p0 = predict_m0(row, fit, budget)
        p1 = predict_m1(row, fit, budget)
        try:
            p2 = predict_m2(row, fit_deg, budget)
        except ValueError:
            p2 = None
        try:
            p3 = predict_m3(row, fit_deg, budget)
        except ValueError:
            p3 = None
        paired.append(
            {
                **row,
                "pred_m0": p0,
                "pred_m1": p1,
                "pred_m2": p2,
                "pred_m3": p3,
                "err_m0": abs(y - p0),
                "err_m1": abs(y - p1),
                "err_m2": abs(y - p2) if p2 is not None else None,
                "err_m3": abs(y - p3) if p3 is not None else None,
            }
        )

    by_cell: dict[tuple[int, int], list[dict]] = defaultdict(list)
    for r in paired:
        by_cell[_cell_key(r)].append(r)
    per_cell: list[dict] = []
    for cell in sorted(by_cell):
        rows = by_cell[cell]
        c_mae0 = statistics.fmean([r["err_m0"] for r in rows])
        c_mae1 = statistics.fmean([r["err_m1"] for r in rows])
        per_cell.append(
            {
                "n": cell[0],
                "m": cell[1],
                "a_hundredths": rows[0].get("a_hundredths"),
                "n_test": len(rows),
                "mean_y": statistics.fmean([r["y"] for r in rows]),
                "mean_width": statistics.fmean([r["width"] for r in rows]),
                "width_std": (
                    statistics.pstdev([float(r["width"]) for r in rows])
                    if len(rows) > 1
                    else 0.0
                ),
                "mean_degree": statistics.fmean([r["degree_mean"] for r in rows]),
                "mae_m0": c_mae0,
                "mae_m1": c_mae1,
                "mae_m2": _mae_cell(rows, "err_m2"),
                "mae_m3": _mae_cell(rows, "err_m3"),
                "improvement": 1 - c_mae1 / c_mae0 if c_mae0 != 0 else None,
                "spearman_width_y": _spearman(
                    [float(r["width"]) for r in rows],
                    [float(r["y"]) for r in rows],
                ),
                "spearman_degree_y": _spearman(
                    [float(r["degree_mean"]) for r in rows],
                    [float(r["y"]) for r in rows],
                ),
                "n_sat": sum(1 for r in rows if r["status"] == "SAT"),
                "n_unsat": sum(1 for r in rows if r["status"] == "UNSAT"),
                "n_unknown": sum(1 for r in rows if r["status"] == "UNKNOWN"),
                "budget_hit_fraction": statistics.fmean(
                    [1.0 if r["timed_out"] else 0.0 for r in rows]
                ),
            }
        )
    # Equal-cell-weighted overall MAEs (DEE-R9-17): the mean of the
    # per-cell MAEs. Cells with no identifiable M2/M3 slope are
    # skipped for those models.
    mae0 = statistics.fmean([c["mae_m0"] for c in per_cell])
    mae1 = statistics.fmean([c["mae_m1"] for c in per_cell])
    mae2 = _mae_cell(per_cell, "mae_m2")
    mae3 = _mae_cell(per_cell, "mae_m3")
    assert mae0 is not None and mae1 is not None
    improvement = 1 - mae1 / mae0 if mae0 != 0 else None
    return {
        "n_test": len(paired),
        "mae_m0": mae0,
        "mae_m1": mae1,
        "mae_m2": mae2,
        "mae_m3": mae3,
        "improvement": improvement,
        "improvement_m2": (1 - mae2 / mae0) if mae2 is not None and mae0 else None,
        "improvement_m3": (1 - mae3 / mae0) if mae3 is not None and mae0 else None,
        "paired": paired,
        "per_cell": per_cell,
    }


def _mae_cell(rows: list[dict], key: str) -> float | None:
    vals = [r[key] for r in rows if r[key] is not None]
    return statistics.fmean(vals) if vals else None


# --- Paired stratified bootstrap (Section 3.10) ---------------------------


def paired_stratified_bootstrap(
    paired_rows: list[dict],
    replicates: int = BOOTSTRAP_REPLICATES,
    seed: int = BOOTSTRAP_SEED,
) -> dict:
    """Paired, stratified percentile bootstrap of the improvement.

    Within each test cell, sample exactly BOOTSTRAP_ROWS_PER_CELL
    (30, Section 3.10: fixed size, regardless of the cell's size)
    rows with replacement, resampling the paired (M0, M1) errors
    together. The fixed draw size applies to every test cell,
    including non-confirmatory cells with fewer than 30 rows: the 30
    draws are taken with replacement from whatever rows the cell
    has. A cell with k < 30 rows is therefore resampled as if it
    were a 30-row cell, so the interval understates that cell's
    sampling variability; for non-confirmatory populations the
    interval is illustrative only (the disposition is INCONCLUSIVE
    by construction). For the confirmatory population the integrity
    gates enforce exactly 30 test rows per cell, so the draw size
    matches the cell size. No assert enforces a minimum cell size,
    because the pilot legitimately has 5 test rows per cell
    (DEE-R9-17 follow-up).
    The replicate improvement is 1 - MAE1 / MAE0 with the
    MAEs equal-cell-weighted (mean of per-cell MAEs), matching
    evaluate() (DEE-R9-17). Fitted models are fixed; only the test
    sample is resampled. Percentiles use linear interpolation
    (NumPy default).
    """
    by_cell: dict[tuple[int, int], list[dict]] = defaultdict(list)
    for r in paired_rows:
        by_cell[_cell_key(r)].append(r)
    cells = sorted(by_cell)
    rng = np.random.default_rng(seed)  # PCG64
    improvements: list[float] = []
    n_undefined = 0
    for _ in range(replicates):
        mae0_sum = 0.0
        mae1_sum = 0.0
        for cell in cells:
            rows = by_cell[cell]
            idx = rng.integers(0, len(rows), size=BOOTSTRAP_ROWS_PER_CELL)
            mae0_sum += (
                sum(rows[int(j)]["err_m0"] for j in idx) / BOOTSTRAP_ROWS_PER_CELL
            )
            mae1_sum += (
                sum(rows[int(j)]["err_m1"] for j in idx) / BOOTSTRAP_ROWS_PER_CELL
            )
        mae0 = mae0_sum / len(cells)
        mae1 = mae1_sum / len(cells)
        if mae0 == 0:
            n_undefined += 1
            continue
        improvements.append(1 - mae1 / mae0)
    arr = np.array(improvements, dtype=float) if improvements else np.array([])
    return {
        "replicates": replicates,
        "seed": seed,
        "n_defined": len(improvements),
        "n_undefined": n_undefined,
        "mean": float(np.mean(arr)) if len(arr) else None,
        "std": float(np.std(arr)) if len(arr) else None,
        "ci_lower_2.5": float(np.percentile(arr, 2.5)) if len(arr) else None,
        "ci_upper_97.5": float(np.percentile(arr, 97.5)) if len(arr) else None,
    }


# --- Integrity and verification gates (Sections 3, 4) --------------------


def integrity_gates(
    rows: list[dict],
    population: str,
    budget: int = BUDGET_B,
) -> dict:
    """Data-integrity gates. Returns failures; empty means they pass.

    Checks: no duplicate (n, m, index) rows; train/test disjoint;
    every test cell has training rows; Y in range; width/decisions
    non-negative; budget-exhausted rows are UNKNOWN (never UNSAT);
    SAT rows carry a checked witness (no INVALID rows); seeds are
    distinct within the population. For the confirmatory population,
    also checks the exact 28-cell / 70-train / 30-test shape.
    """
    failures: list[str] = []
    keys = [(r["n"], r["m"], r.get("index")) for r in rows]
    if len(set(keys)) != len(keys):
        failures.append("duplicate (n, m, index) rows present")
    train_keys = {
        (r["n"], r["m"], r.get("index"))
        for r in rows
        if r["split"] == "train"
    }
    test_keys = {
        (r["n"], r["m"], r.get("index"))
        for r in rows
        if r["split"] == "test"
    }
    if train_keys & test_keys:
        failures.append("train/test split overlap: same (n, m, index) in both")
    train_cells = {_cell_key(r) for r in rows if r["split"] == "train"}
    test_cells = {_cell_key(r) for r in rows if r["split"] == "test"}
    missing_train = test_cells - train_cells
    if missing_train:
        failures.append(f"test cells with no training rows: {sorted(missing_train)}")
    for r in rows:
        # An ERROR row (or a malformed record) carries None for y /
        # decisions / width; report it as a failure instead of
        # crashing on float(None) (DEE-R9-04). The row is skipped for
        # the numeric checks below.
        none_fields = [k for k in ("y", "decisions", "width") if r.get(k) is None]
        if none_fields:
            failures.append(
                f"row {r.get('index')}: None {', '.join(none_fields)} "
                "(ERROR row or malformed record)"
            )
            continue
        if not (0.0 <= float(r["y"]) <= math.log1p(budget) + 1e-12):
            failures.append(f"Y out of range in row {r.get('index')}")
        if int(r["width"]) < 0 or int(r["decisions"]) < 0:
            failures.append("negative width or decisions")
        if r["timed_out"] and r["status"] != "UNKNOWN":
            failures.append("budget-exhausted row not labelled UNKNOWN")
        if r["status"] == "SAT" and not r.get("verified"):
            failures.append("SAT row without a checked witness (INVALID)")
        if r["status"] == "UNKNOWN" and r.get("satisfiable"):
            failures.append("UNKNOWN row claims satisfiable=True")
    seeds = [r.get("seed") for r in rows if r.get("seed") is not None]
    if len(set(seeds)) != len(seeds):
        failures.append("duplicate seeds within the population")
    if population == "confirmatory":
        if len(test_cells) != 28:
            failures.append(
                f"confirmatory population must have 28 test cells, got {len(test_cells)}"
            )
        for cell in sorted(test_cells):
            n_test = sum(
                1 for r in rows if r["split"] == "test" and _cell_key(r) == cell
            )
            n_train = sum(
                1 for r in rows if r["split"] == "train" and _cell_key(r) == cell
            )
            if n_test != 30 or n_train != 70:
                failures.append(
                    f"cell {cell}: expected 70 train / 30 test, got {n_train} / {n_test}"
                )
                break
    return {"passed": not failures, "failures": failures}


def verification_gates(rows: list[dict]) -> dict:
    """Verification gates (Section 4.1).

    SAT rows must be SAT_WITNESS_CHECKED. UNSAT rows pass only with
    UNSAT_PROOF_CHECKED or UNSAT_KNOWN_BY_CONSTRUCTION. Solver
    agreement alone (UNSAT_SOLVER_AGREEMENT_ONLY) is useful
    cross-checking, not proof evidence, so it fails this gate.
    UNKNOWN rows make no claim and are not gated here.
    """
    failures: list[str] = []
    n_unsat = sum(1 for r in rows if r["status"] == "UNSAT")
    n_unsat_proof = sum(
        1
        for r in rows
        if r["status"] == "UNSAT"
        and r.get("verification_status")
        in {"UNSAT_PROOF_CHECKED", "UNSAT_KNOWN_BY_CONSTRUCTION"}
    )
    n_sat_unchecked = sum(
        1
        for r in rows
        if r["status"] == "SAT"
        and r.get("verification_status") != "SAT_WITNESS_CHECKED"
    )
    if n_sat_unchecked:
        failures.append(f"{n_sat_unchecked} SAT rows without a checked witness")
    if n_unsat and n_unsat_proof < n_unsat:
        failures.append(
            f"{n_unsat - n_unsat_proof} of {n_unsat} UNSAT rows lack a "
            "proof-checked verification status "
            "(solver agreement alone is not proof evidence)"
        )
    return {
        "passed": not failures,
        "failures": failures,
        "n_unsat": n_unsat,
        "n_unsat_proof_checked": n_unsat_proof,
    }


# --- Primary disposition ---------------------------------------------------


def primary_disposition(
    evaluation: dict | None,
    bootstrap: dict | None,
    gates: dict,
    verification: dict,
    fit: dict,
    reproducibility: dict | None = None,
    eval_error: str | None = None,
    n_error_rows: int = 0,
) -> dict:
    """One machine-readable primary disposition (Section 3.10).

    PASS requires gates passing, point improvement >= 5%, and the
    bootstrap interval's lower endpoint > 0. FAIL is point
    improvement < 5% with gates passing. Everything else is
    INCONCLUSIVE. The effort-only disposition (ignoring the
    verification gate, but still requiring the integrity gates) is
    reported separately so the signal is not hidden when verification
    is the blocker. A reproducibility gate that was not evaluated or
    that failed also forces INCONCLUSIVE (Section 3.10, DEE-R9-18).
    Any excluded ERROR row also forces INCONCLUSIVE: it is missing
    data, not a measurement (DEE-R9-04 follow-up).
    """
    reasons: list[str] = []
    if not gates["passed"]:
        reasons.extend(gates["failures"])
    if not verification["passed"]:
        reasons.extend(verification["failures"])
    if reproducibility is not None:
        if not reproducibility.get("evaluated"):
            reasons.append(
                "reproducibility gate not evaluated (no manifest supplied)"
            )
        elif not reproducibility.get("passed"):
            reasons.extend(reproducibility.get("failures", []))
    if n_error_rows > 0:
        reasons.append(
            f"{n_error_rows} ERROR row(s) excluded as missing data "
            "(rerun them)"
        )
    effort_only: str | None = None
    if not gates["passed"]:
        # The effort signal cannot be trusted when the data itself
        # fails an integrity gate (DEE-R9-19).
        effort_only = "INCONCLUSIVE"
    elif evaluation is not None and evaluation["improvement"] is not None:
        effort_only = (
            "PASS" if evaluation["improvement"] >= EFFECT_THRESHOLD else "FAIL"
        )
        if bootstrap is not None and bootstrap["ci_lower_2.5"] is not None:
            if (
                evaluation["improvement"] >= EFFECT_THRESHOLD
                and bootstrap["ci_lower_2.5"] <= 0
            ):
                effort_only = "INCONCLUSIVE"
        elif evaluation["improvement"] >= EFFECT_THRESHOLD:
            effort_only = "INCONCLUSIVE"
    if fit.get("beta") is None:
        reasons.append("M1 slope denominator is zero (width unidentifiable)")
    if evaluation is None:
        reasons.append("evaluation could not be computed")
    elif evaluation["improvement"] is None:
        reasons.append("MAE_0 is zero, so percentage improvement is undefined")
    if bootstrap is not None and bootstrap["n_undefined"] > 0:
        reasons.append(
            f"bootstrap had {bootstrap['n_undefined']} undefined replicates "
            "(resampled MAE_0 == 0)"
        )

    if reasons:
        disposition = "INCONCLUSIVE"
    elif evaluation is not None and evaluation["improvement"] is not None:
        if (
            evaluation["improvement"] >= EFFECT_THRESHOLD
            and bootstrap is not None
            and bootstrap["ci_lower_2.5"] is not None
            and bootstrap["ci_lower_2.5"] > 0
        ):
            disposition = "PASS"
        elif evaluation["improvement"] < EFFECT_THRESHOLD:
            disposition = "FAIL"
        else:
            disposition = "INCONCLUSIVE"
            if bootstrap is None:
                # The interval is unavailable, not "including zero"
                # (DEE-R9-02).
                reasons.append(
                    "bootstrap unavailable"
                    + (f": {eval_error}" if eval_error else "")
                )
            else:
                reasons.append(
                    "point improvement >= 5% but bootstrap interval includes zero"
                )
    else:
        disposition = "INCONCLUSIVE"
    return {
        "disposition": disposition,
        "effect_threshold": EFFECT_THRESHOLD,
        "point_improvement": (
            evaluation["improvement"] if evaluation is not None else None
        ),
        "bootstrap_ci_lower_2.5": (
            bootstrap["ci_lower_2.5"] if bootstrap is not None else None
        ),
        "bootstrap_ci_upper_97.5": (
            bootstrap["ci_upper_97.5"] if bootstrap is not None else None
        ),
        "effort_only_disposition": effort_only,
        "reasons": reasons,
    }


