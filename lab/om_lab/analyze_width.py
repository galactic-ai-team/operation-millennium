def count_error_records(records: list[dict]) -> int:
    """Number of runner records with ``status == "ERROR"`` (missing data)."""
    return sum(1 for rec in records if rec.get("status") == "ERROR")


def records_to_rows(records: list[dict]) -> list[dict]:
    """Convert runner JSONL records into analysis rows.

    Expected record fields: ``n_vars``, ``n_clauses``, ``decisions``,
    ``timed_out``, ``satisfiable``. Optional: ``seed``, ``index``,
    ``split``, ``a_hundredths``, ``width``, ``degree_mean``,
    ``verification_status``, ``problem``. When ``width`` /
    ``degree_mean`` are absent and the record is a ``random_3sat``
    instance with a seed, the instance is regenerated exactly and the
    features are computed from it (as in ``analyze_hardness``).

    Explicit ``status`` (added with Claude's OM-C001-R2 runner): when a
    record carries ``status``, it must agree with ``satisfiable`` /
    ``timed_out`` or a ``ValueError`` is raised. ``status == "ERROR"``
    marks an infrastructure failure (watchdog / worker crash) that
    survived reruns; it is missing experimental data (Section 3.6), so it
    is excluded here rather than read as UNSAT or UNKNOWN. For the
    confirmatory population the integrity gate then reports the missing
    row and the primary disposition is INCONCLUSIVE.
    """
    rows: list[dict] = []
    n_error = count_error_records(records)
    if n_error:
        warnings.warn(
            f"{n_error} ERROR record(s) treated as missing data (rerun them)",
            stacklevel=2,
        )
    for rec in records:
        explicit_status = rec.get("status")
        if explicit_status is not None:
            if explicit_status == "ERROR":
                continue
            implied = status_from_solver(
                bool(rec["satisfiable"]), bool(rec.get("timed_out", False))
            )
            if explicit_status != implied:
                raise ValueError(
                    f"record status {explicit_status!r} contradicts "
                    f"satisfiable/timed_out (which imply {implied!r})"
                )
        n = int(rec["n_vars"])
        m = int(rec["n_clauses"])
        width = rec.get("width")
        degree_mean = rec.get("degree_mean")
        if width is None or degree_mean is None:
            seed = rec.get("seed")
            if rec.get("problem") != "random_3sat" or not isinstance(seed, int):
                raise ValueError(
                    "record lacks width/degree_mean and cannot be "
                    "regenerated (needs problem=random_3sat and an int seed)"
                )
            inst = generate_random_3sat(n_vars=n, n_clauses=m, seed=seed)
            if width is None:
                width = primal_min_fill_width(n, inst.clauses).width
            if degree_mean is None:
                degree_mean = extract_features_from_clauses(
                    n, inst.clauses
                ).to_dict()["cooccurrence_degree_mean"]
        split = rec.get("split")
        index = rec.get("index")
        if split is None and isinstance(index, int):
            split = "train" if index <= TRAIN_INDEX_MAX else "test"
        if split not in {"train", "test"}:
            raise ValueError(
                "record needs an explicit split (train/test) or an index"
            )
        rows.append(
            make_row(
                n=n,
                m=m,
                a_hundredths=rec.get("a_hundredths"),
                index=index,
                split=split,
                seed=rec.get("seed"),
                width=int(width),
                degree_mean=float(degree_mean),
                decisions=int(rec["decisions"]),
                timed_out=bool(rec.get("timed_out", False)),
                satisfiable=bool(rec["satisfiable"]),
                verified=bool(rec.get("verified", False)),
                verification_status=rec.get("verification_status"),
            )
        )
    return rows


def read_jsonl(path: str | Path) -> list[dict]:
    records: list[dict] = []
    with Path(path).open(encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if line:
                records.append(json.loads(line))
    return records


# --- Pilot generation (separate population, NOT confirmatory) -------------


def generate_pilot_rows(
    n_values: list[int] | None = None,
    a_values: list[int] | None = None,
    n_train: int = 10,
    n_test: int = 5,
    budget: int = BUDGET_B,
) -> list[dict]:
    """Generate a small pilot population with pilot seeds.

    This exists to validate the analysis machinery end to end. Pilot
    seeds use a different prefix from the confirmatory seeds, pilot
    indices are 0..(n_train+n_test-1) per cell, and the population is
    labelled ``pilot`` everywhere, so no pilot row can be mistaken
    for a confirmatory row. Pilot rows are generated by calling
    ``solve_dpll`` directly (see the module docstring for why the
    harness is not used: it rejects budget-exhausted runs).
    """
    # Imported lazily so ``--records`` mode does not need the solver stack.
    from om_lab.solvers import solve_dpll

    n_values = n_values if n_values is not None else [30]
    a_values = a_values if a_values is not None else [400, 426, 460]
    rows: list[dict] = []
    for n in n_values:
        for a in a_values:
            m = clause_count(n, a)
            for i in range(n_train + n_test):
                seed = pilot_seed(n, a, i)
                inst = generate_random_3sat(n_vars=n, n_clauses=m, seed=seed)
                result = primal_min_fill_width(n, inst.clauses)
                # Internal consistency: independent replay must agree.
                replayed = replay_elimination_order(
                    n, inst.clauses, result.ordering
                )
                if replayed != result.width:
                    raise AssertionError(
                        f"replay width {replayed} != min-fill width "
                        f"{result.width} for pilot instance n={n} A={a} i={i}"
                    )
                degree_mean = extract_features_from_clauses(
                    n, inst.clauses
                ).to_dict()["cooccurrence_degree_mean"]
                # Width under reversed variable IDs (secondary 8).
                reversed_clauses = [
                    [n + 1 - abs(lit) if lit > 0 else -(n + 1 - abs(lit)) for lit in c]
                    for c in inst.clauses
                ]
                width_reversed = primal_min_fill_width(
                    n, reversed_clauses
                ).width
                res = solve_dpll(n, inst.clauses, max_decisions=budget)
                if res.satisfiable and not res.verified:
                    raise AssertionError(
                        "DPLL returned an unverified SAT model "
                        f"(n={n} A={a} i={i}); refusing to log it"
                    )
                rows.append(
                    make_row(
                        n=n,
                        m=m,
                        a_hundredths=a,
                        index=i,
                        split="train" if i < n_train else "test",
                        seed=seed,
                        width=result.width,
                        degree_mean=degree_mean,
                        decisions=res.decisions,
                        timed_out=res.timed_out,
                        satisfiable=res.satisfiable,
                        verified=res.verified,
                        width_reversed=width_reversed,
                        budget=budget,
                    )
                )
    return rows


# --- Plots and outputs -----------------------------------------------------


def plot_per_cell_mae(per_cell: list[dict], path: Path) -> Path:
    labels = [f"n{c['n']}\nα{c['a_hundredths']/100:.2f}" if c.get("a_hundredths") else f"n{c['n']} m{c['m']}" for c in per_cell]
    mae0 = [c["mae_m0"] for c in per_cell]
    mae1 = [c["mae_m1"] for c in per_cell]
    x = np.arange(len(per_cell))
    fig, ax = plt.subplots(figsize=(max(8, len(per_cell) * 0.45), 4.5))
    ax.bar(x - 0.2, mae0, width=0.4, label="M0 (cell mean)")
    ax.bar(x + 0.2, mae1, width=0.4, label="M1 (cell mean + width)")
    ax.set_xticks(x)
    ax.set_xticklabels(labels, fontsize=7)
    ax.set_ylabel("Held-out MAE on Y = ln(1 + min(D, B))")
    ax.set_title("Per-cell held-out MAE: M0 vs M1 [Claim Level: Empirical Observation]")
    ax.legend(loc="best", fontsize="small")
    ax.grid(True, axis="y", alpha=0.3)
    fig.tight_layout()
    fig.savefig(path, dpi=150)
    plt.close(fig)
    return path


def plot_width_vs_effort(test_rows: list[dict], path: Path) -> Path:
    colours = {"SAT": "#1f77b4", "UNSAT": "#d62728", "UNKNOWN": "#ff7f0e"}
    fig, ax = plt.subplots(figsize=(7, 5))
    for status in ("SAT", "UNSAT", "UNKNOWN"):
        group = [r for r in test_rows if r["status"] == status]
        if group:
            ax.scatter(
                [r["width"] for r in group],
                [r["y"] for r in group],
                label=status,
                color=colours[status],
                alpha=0.7,
                s=24,
            )
    ax.set_xlabel("primal_min_fill_width")
    ax.set_ylabel("Y = ln(1 + min(D, B))  [DPLL branch attempts]")
    ax.set_title("Held-out width vs capped DPLL effort [Claim Level: Empirical Observation]")
    ax.legend(loc="best")
    ax.grid(True, alpha=0.3)
    fig.tight_layout()
    fig.savefig(path, dpi=150)
    plt.close(fig)
    return path


def write_outputs(
    summary: dict, evaluation_paired: list[dict] | None, out_dir: str | Path
) -> dict:
    """Write analysis JSON, primary disposition, per-cell CSV, plots."""
    out_path = Path(out_dir)
    out_path.mkdir(parents=True, exist_ok=True)
    analysis_path = out_path / "width_analysis.json"
    analysis_path.write_text(json.dumps(summary, indent=2), encoding="utf-8")
    primary_path = out_path / "primary_result.json"
    primary_path.write_text(
        json.dumps(
            {
                "claim_level": CLAIM_LEVEL,
                "experiment": "OM-C001-R2",
                "population": summary["population"],
                **summary["primary_disposition"],
            },
            indent=2,
        ),
        encoding="utf-8",
    )
    per_cell = (
        summary["evaluation"]["per_cell"] if summary["evaluation"] else []
    )
    csv_path = out_path / "per_cell.csv"
    if per_cell:
        with csv_path.open("w", newline="", encoding="utf-8") as f:
            writer = csv.DictWriter(f, fieldnames=list(per_cell[0].keys()))
            writer.writeheader()
            writer.writerows(per_cell)
        plot_per_cell_mae(per_cell, out_path / "per_cell_mae.png")
    else:
        csv_path.write_text("", encoding="utf-8")
    if evaluation_paired:
        test_rows = [
            {k: r[k] for k in ("width", "y", "status") if k in r}
            for r in evaluation_paired
        ]
        plot_width_vs_effort(test_rows, out_path / "width_vs_effort.png")
    return {
        "analysis_json": str(analysis_path),
        "primary_result_json": str(primary_path),
        "per_cell_csv": str(csv_path),
    }


def _print_report(summary: dict) -> None:
    disp = summary["primary_disposition"]
    print(f"[Claim Level: {summary['claim_level']}]  Experiment OM-C001-R2")
    print(f"Population: {summary['population']}")
    print(
        f"Rows: {summary['counts']['n_rows']} "
        f"(train {summary['counts']['n_train']}, "
        f"test {summary['counts']['n_test']}, "
        f"cells {summary['counts']['n_cells_test']} test)"
    )
    print(f"Primary disposition: {disp['disposition']}")
    if disp["point_improvement"] is not None:
        print(f"Point improvement (M1 vs M0): {disp['point_improvement']:+.3f}")
    if disp["bootstrap_ci_lower_2.5"] is not None:
        print(
            "Bootstrap 95% interval: "
            f"[{disp['bootstrap_ci_lower_2.5']:+.3f}, "
            f"{disp['bootstrap_ci_upper_97.5']:+.3f}] "
            f"(replicates={summary['bootstrap']['replicates']}, "
            f"seed={summary['bootstrap']['seed']})"
        )
    if disp["effort_only_disposition"] is not None:
        print(
            "Effort-only disposition (ignoring verification gate): "
            f"{disp['effort_only_disposition']}"
        )
    for reason in disp["reasons"]:
        print(f"  - {reason}")
    if summary["evaluation"] is not None:
        ev = summary["evaluation"]
        def _fmt(v):
            return f"{v:.4f}" if v is not None else "None"

        print(
            f"MAE: M0={_fmt(ev['mae_m0'])}  M1={_fmt(ev['mae_m1'])}  "
            f"M2={_fmt(ev['mae_m2'])}  M3={_fmt(ev['mae_m3'])}"
        )
        if ev["improvement_m2"] is not None:
            print(f"Degree-adjusted improvement: M2={ev['improvement_m2']:+.3f}")
        if ev["improvement_m3"] is not None:
            print(f"Degree-adjusted improvement: M3={ev['improvement_m3']:+.3f}")
    if summary["relabel_sensitivity"] is not None:
        rs = summary["relabel_sensitivity"]
        print(
            "Relabelling sensitivity (reversed IDs): "
            f"width changed in {rs['fraction_width_changed']:.2f} of "
            f"{rs['n_instances']} instances, "
            f"mean |ΔW|={rs['mean_abs_width_change']:.2f}"
        )
    print("Limitations (see JSON for the full list):")
    for item in summary["limitations"]:
        print(f"  - {item}")


def main() -> None:
    parser = argparse.ArgumentParser(
        description=(
            "Frozen OM-C001-R2 prediction analysis. "
            "[Claim Level: Empirical Observation] "
            "Analyses --records rows, or a small pilot population "
            "with --pilot. It never generates confirmatory seeds; "
            "confirmatory execution is Lumi-authorised, via Claude's "
            "runner, and analysed here with --records "
            "--population confirmatory."
        )
    )
    parser.add_argument(
        "--records", type=str, default=None,
        help="Runner JSONL records to analyse.",
    )
    parser.add_argument(
        "--population", type=str, default=None,
        choices=["confirmatory", "pilot", "synthetic"],
        help="Population label for the rows. Required with --records.",
    )
    parser.add_argument(
        "--pilot", action="store_true",
        help="Generate a small pilot population (pilot seeds, not confirmatory).",
    )
    parser.add_argument("--pilot-n-train", type=int, default=10)
    parser.add_argument("--pilot-n-test", type=int, default=5)
    parser.add_argument(
        "--pilot-n-values", type=int, nargs="+", default=[30],
    )
    parser.add_argument(
        "--pilot-a-values", type=int, nargs="+", default=[400, 426, 460],
    )
    parser.add_argument(
        "--reproducibility-manifest", type=str, default=None,
        help="Runner freeze manifest JSON to check the reproducibility "
        "gate against (Section 3.10). Without it, the gate is "
        "unevaluated and a confirmatory disposition is INCONCLUSIVE.",
    )
    parser.add_argument("--out-dir", type=str, default="results")
    args = parser.parse_args()

    if args.pilot and args.records:
        parser.error("use either --pilot or --records, not both")
    if args.pilot:
        rows = generate_pilot_rows(
            n_values=args.pilot_n_values,
            a_values=args.pilot_a_values,
            n_train=args.pilot_n_train,
            n_test=args.pilot_n_test,
        )
        population = "pilot"
        print(f"Generated {len(rows)} pilot rows (pilot seeds, not confirmatory).")
    elif args.records:
        if args.population is None:
            parser.error("--population is required with --records")
        records = read_jsonl(args.records)
        n_error = count_error_records(records)
        if n_error:
            print(
                f"WARNING: {n_error} ERROR record(s) are missing data and were "
                "excluded; rerun them with the same instance and budget."
            )
        rows = records_to_rows(records)
        population = args.population
    else:
        parser.error("specify --pilot or --records")

    repro_manifest = None
    if args.reproducibility_manifest:
        with open(args.reproducibility_manifest, encoding="utf-8") as handle:
            repro_manifest = json.load(handle)
    summary = analyze_rows(rows, population, reproducibility_manifest=repro_manifest)
    # Plot points (width, y, status) for held-out rows.
    evaluation_paired = None
    if summary["evaluation"] is not None:
        evaluation_paired = [
            {"width": r["width"], "y": r["y"], "status": r["status"]}
            for r in rows
            if r["split"] == "test"
        ]
    paths = write_outputs(summary, evaluation_paired, args.out_dir)
    _print_report(summary)
    print(f"\nWrote: {paths['analysis_json']}")
    print(f"Wrote: {paths['primary_result_json']}")
    print(f"Wrote: {paths['per_cell_csv']}")


if __name__ == "__main__":
    main()
