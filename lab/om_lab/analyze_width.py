"""Frozen prediction analysis for preregistration OM-C001-R2.

Implements Section 3 of ``docs/phase3/DISCOVERY_ROUND_01.md`` exactly.
Read that section before changing anything in this file: the model,
the metric, the bootstrap, and the decision rules are frozen, and no
confirmatory feature selection, hyperparameter tuning, or test-set
fitting is permitted.

[Claim Level: Empirical Observation] for every result this script
produces. A PASS here would be a finite-population prediction result,
not a proof about treewidth, worst-case complexity, or P vs NP.

What this script does and does not do
--------------------------------------
* It analyses rows. A row is one DPLL run on one instance, with the
  structural features (primal min-fill width, co-occurrence mean
  degree) computed from the formula alone, the capped log-effort
  ``Y = ln(1 + min(D, B))`` with ``B = 10000``, the cell ``(n, m)``,
  and the train/test split. Rows arrive either from a JSONL records
  file (``--records``, the interface for Claude's frozen runner) or
  from a small *pilot* population generated here with a different
  seed prefix (``--pilot``).
* It does **not** generate the confirmatory population. The
  confirmatory seeds (Section 3.5, seed material ``"OM-C001-R2|n|A|i"``)
  must only be run after Lumi freezes the implementation and
  authorises confirmatory execution (Section 8). There is deliberately
  no ``--confirmatory`` generation mode in this script. Running the
  confirmatory seeds before that authorisation would unblind the test.
* It does **not** use the existing ``run_cnf_harness`` to generate
  rows, because that harness still raises on budget-exhausted runs
  (Section 4.2, still open on dev): a DPLL run that exhausts its
  budget returns ``verified=False, timed_out=True`` and the harness
  rejects it instead of logging an UNKNOWN row. Pilot rows are
  therefore generated by calling ``solve_dpll`` directly and mapping
  the result to SAT / UNSAT / UNKNOWN explicitly. That generation path
  is a pilot/smoke implementation, not Claude's frozen runner.

Primary models (Section 3.8, training rows only)
------------------------------------------------
* Cell ``c`` is the exact pair ``(n, m)``.
* M0: per-cell training mean of ``Y``.
* M1: per-cell training mean of ``Y`` plus one shared slope ``beta``
  on within-cell-centred width. ``beta`` is the pooled within-cell
  least-squares slope over training rows only.
* Both predictions are clipped to ``[0, ln(1 + B)]``.
* If the slope denominator is zero, M1 is unidentifiable and the
  primary disposition is INCONCLUSIVE. If ``MAE_0 == 0``, the
  percentage improvement is undefined and the disposition is
  INCONCLUSIVE.

Primary statistic (Section 3.9) and bootstrap (Section 3.10)
-------------------------------------------------------------
``improvement = 1 - MAE_1 / MAE_0`` over the held-out rows.
Uncertainty is a paired, stratified percentile bootstrap: 10000
replicates, NumPy Generator (PCG64), seed 9012026, resampling paired
(M0, M1) errors within each test cell with replacement, equal cell
weights, 2.5th/97.5th percentiles by linear interpolation. The fitted
models stay fixed during the bootstrap.

Decision rules (Section 3.10): PASS requires the data-integrity and
verification gates to pass, point improvement >= 5%, and the
bootstrap interval's lower endpoint > 0. FAIL is point improvement
< 5% with gates passing. Anything else (including missing rows,
failed verification gates, undefined baseline/slope, or an interval
including zero) is INCONCLUSIVE.

Verification gates (Section 4): SAT rows must carry a checked
witness; UNKNOWN rows must be retained and never counted as UNSAT;
and UNSAT rows must carry a proof-checked verification status
(``UNSAT_PROOF_CHECKED`` or ``UNSAT_KNOWN_BY_CONSTRUCTION``) for the
verification gate to pass. Solver agreement alone is *not* proof
evidence, so UNSAT rows labelled only as solver agreement fail the
verification gate and the primary disposition is INCONCLUSIVE, even
if the effort-only improvement would otherwise pass. The
effort-only disposition is reported separately (labelled as such) so
that signal is not hidden.

Secondary analyses (Section 3.11)
----------------------------------
* Degree-adjusted models, fitted exactly like M1 but on centred
  co-occurrence mean degree: M2 (degree only) and M3 (degree + width,
  joint least squares). Compared on the same held-out MAE statistic.
* Per-cell Spearman correlations between width and effort (every cell,
  including undefined ones), per-cell error summaries, and separate
  SAT / UNSAT / UNKNOWN summaries with budget-hit rates.
* The original C001-style completed-only regression, CDCL responses,
  and min-degree / incidence-width comparisons are *not* implemented
  here; they are separate secondary analyses (see Limitations in the
  output). No secondary result can rescue a failed primary test, and
  no post-hoc feature may be promoted without a new test protocol.
"""

