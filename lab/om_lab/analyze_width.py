def _sha256_file(path: Path) -> str | None:
    try:
        return hashlib.sha256(path.read_bytes()).hexdigest()
    except OSError:
        return None


def _reproducibility(population: str) -> dict:
    lab_dir = Path(__file__).resolve().parent
    files = {
        name: _sha256_file(lab_dir / name)
        for name in (
            "generators.py",
            "solvers.py",
            "features.py",
            "width_features.py",
            "analyze_width.py",
        )
    }
    return {
        "population": population,
        "python_version": sys.version.split()[0],
        "platform": platform.platform(),
        "numpy_version": np.__version__,
        "matplotlib_version": matplotlib.__version__,
        "budget_b": BUDGET_B,
        "bootstrap_replicates": BOOTSTRAP_REPLICATES,
        "bootstrap_seed": BOOTSTRAP_SEED,
        "effect_threshold": EFFECT_THRESHOLD,
        "source_file_sha256": files,
    }


def reproducibility_gates(frozen: dict | None) -> dict:
    """Pass/fail reproducibility gate (Section 3.10, DEE-R9-18).

    Compares the current NumPy version and the SHA-256 of the five
    source files this analysis depends on against a frozen manifest:
    the runner's freeze manifest JSON (see
    ``width_experiment.draft_freeze_manifest``), which carries
    ``environment.packages.numpy`` and ``source_sha256``. Only the
    files this analysis depends on are compared; extra files in the
    frozen manifest (e.g. the proof checker) are the runner's
    business, not this analysis's. ``frozen is None`` means the gate
    was not evaluated: that is a failure, not a pass -- a
    confirmatory disposition must never rest on an unevaluated gate.
    """
    current = _reproducibility("confirmatory")
    checked = {
        "numpy_version": current["numpy_version"],
        "source_sha256": current["source_file_sha256"],
    }
    if frozen is None:
        return {
            "evaluated": False,
            "passed": False,
            "failures": ["no reproducibility manifest supplied; gate not evaluated"],
            "checked": checked,
        }
    failures: list[str] = []
    packages = (frozen.get("environment") or {}).get("packages") or {}
    frozen_numpy = packages.get("numpy")
    if frozen_numpy is None:
        failures.append("frozen manifest has no numpy version")
    elif frozen_numpy != current["numpy_version"]:
        failures.append(
            f"numpy version differs: frozen {frozen_numpy} vs "
            f"current {current['numpy_version']}"
        )
    frozen_hashes = frozen.get("source_sha256") or {}
    if not frozen_hashes:
        failures.append("frozen manifest has no source hashes")
    else:
        for name, digest in current["source_file_sha256"].items():
            if name not in frozen_hashes:
                failures.append(f"frozen manifest lacks source hash for {name}")
            elif frozen_hashes[name] != digest:
                failures.append(f"source hash differs for {name}")
    return {
        "evaluated": True,
        "passed": not failures,
        "failures": failures,
        "checked": checked,
    }


def analyze_rows(
    rows: list[dict],
    population: str,
    bootstrap_replicates: int = BOOTSTRAP_REPLICATES,
    bootstrap_seed: int = BOOTSTRAP_SEED,
    budget: int = BUDGET_B,
    reproducibility_manifest: dict | None = None,
) -> dict:
    """Run the frozen OM-C001-R2 analysis over already-built rows.

    ``population`` must be one of ``"confirmatory"``, ``"pilot"``, or
    ``"synthetic"``. For a non-confirmatory population the primary
    disposition is INCONCLUSIVE by construction (the frozen
    confirmatory test has not been run); the effort statistics are
    still computed and reported so the machinery can be validated.
    No feature is selected, tuned, or changed based on these rows.
    ERROR rows are excluded as missing data, mirroring
    records_to_rows, and counted (DEE-R9-04). Row invariant:
    ``decisions`` is always a non-negative int; only ERROR rows
    have None.
    ``reproducibility_manifest`` is the runner's freeze manifest
    JSON, or None to leave the reproducibility gate unevaluated --
    which forces INCONCLUSIVE for the confirmatory population
    (DEE-R9-18).
    """
    if population not in {"confirmatory", "pilot", "synthetic"}:
        raise ValueError(f"unknown population {population!r}")
    n_error_rows = sum(1 for r in rows if r.get("status") == "ERROR")
    if n_error_rows:
        rows = [r for r in rows if r.get("status") != "ERROR"]
    train_rows = [r for r in rows if r["split"] == "train"]
    test_rows = [r for r in rows if r["split"] == "test"]
    gates = integrity_gates(rows, population, budget=budget)
    verification = verification_gates(rows)
    reproducibility = reproducibility_gates(reproducibility_manifest)
    fit = fit_m0_m1(train_rows) if train_rows else {"beta": None}
    fit_deg = fit_degree_adjusted(train_rows) if train_rows else {}
    evaluation: dict | None = None
    bootstrap: dict | None = None
    eval_error: str | None = None
    if fit.get("beta") is not None and test_rows and gates["passed"]:
        try:
            evaluation = evaluate(test_rows, fit, fit_deg, budget=budget)
            bootstrap = paired_stratified_bootstrap(
                evaluation["paired"],
                replicates=bootstrap_replicates,
                seed=bootstrap_seed,
            )
        except (ValueError, KeyError) as exc:  # e.g. no test rows, MAE undefined
            eval_error = str(exc)
    elif fit.get("beta") is not None and test_rows and not gates["passed"]:
        # Compute the effort statistics anyway (labelled as such) so a
        # gate failure does not hide the signal; the disposition stays
        # INCONCLUSIVE because the gates failed.
        try:
            evaluation = evaluate(test_rows, fit, fit_deg, budget=budget)
            bootstrap = paired_stratified_bootstrap(
                evaluation["paired"],
                replicates=bootstrap_replicates,
                seed=bootstrap_seed,
            )
        except (ValueError, KeyError) as exc:
            eval_error = str(exc)
    disposition = primary_disposition(
        evaluation, bootstrap, gates, verification, fit,
        reproducibility=reproducibility, eval_error=eval_error,
        n_error_rows=n_error_rows,
    )
    if population != "confirmatory":
        disposition = {
            **disposition,
            "disposition": "INCONCLUSIVE",
            "reasons": disposition["reasons"]
            + [
                f"population is {population!r}, not the frozen "
                "confirmatory population; the confirmatory test has "
                "not been run"
            ],
        }

    # Status summaries (secondary, Section 3.11 items 4-5).
    status_summary: dict[str, dict] = {}
    for status in ("SAT", "UNSAT", "UNKNOWN"):
        group = [r for r in test_rows if r["status"] == status]
        if group:
            status_summary[status] = {
                "n_test": len(group),
                "mean_y": statistics.fmean([r["y"] for r in group]),
                "median_decisions": statistics.median(
                    [r["decisions"] for r in group]
                ),
                "budget_hit_fraction": statistics.fmean(
                    [1.0 if r["timed_out"] else 0.0 for r in group]
                ),
            }
    # Relabelling sensitivity (secondary, Section 3.11 item 8), when
    # the rows carry a reversed-ID width.
    relabelled = [r for r in rows if r.get("width_reversed") is not None]
    relabel_sensitivity: dict | None = None
    if relabelled:
        deltas = [
            int(r["width_reversed"]) - int(r["width"]) for r in relabelled
        ]
        relabel_sensitivity = {
            "n_instances": len(relabelled),
            "fraction_width_changed": statistics.fmean(
                [1.0 if d != 0 else 0.0 for d in deltas]
            ),
            "mean_abs_width_change": statistics.fmean([abs(d) for d in deltas]),
            "max_abs_width_change": max(abs(d) for d in deltas),
            "note": (
                "Width under reversed variable IDs. A non-zero change "
                "shows min-fill width is not a relabelling invariant; "
                "it is a deterministic heuristic bound, not exact "
                "treewidth."
            ),
        }

    return {
        "claim_level": CLAIM_LEVEL,
        "experiment": "OM-C001-R2",
        "population": population,
        "scope": (
            "Random 3-SAT only, finite n and seeds. Correlations and "
            "MAE improvements are descriptive; they do not establish "
            "causation, do not generalise to structured instances, "
            "and say nothing about worst-case complexity or P vs NP."
        ),
        "counts": {
            "n_rows": len(rows),
            "n_train": len(train_rows),
            "n_test": len(test_rows),
            "n_cells_train": len({_cell_key(r) for r in train_rows}),
            "n_cells_test": len({_cell_key(r) for r in test_rows}),
            "n_error_rows": n_error_rows,
        },
        "integrity_gates": gates,
        "verification_gates": verification,
        "reproducibility_gates": reproducibility,
        "fit_m0_m1": {
            "beta": fit.get("beta"),
            "slope_denominator": fit.get("slope_denominator"),
            "slope_numerator": fit.get("slope_numerator"),
            "n_train": fit.get("n_train"),
            "width_mean": fit.get("width_mean"),
            "width_std": fit.get("width_std"),
            "cell_mean_y": (
                {f"{n},{m}": v for (n, m), v in fit["cell_mean_y"].items()}
                if "cell_mean_y" in fit
                else {}
            ),
            "cell_mean_width": (
                {f"{n},{m}": v for (n, m), v in fit["cell_mean_width"].items()}
                if "cell_mean_width" in fit
                else {}
            ),
        },
        "fit_degree_adjusted": {
            "m2_beta_degree": fit_deg.get("m2_beta_degree"),
            "m2_denominator": fit_deg.get("m2_denominator"),
            "m3": fit_deg.get("m3"),
            "m3_determinant": fit_deg.get("m3_determinant"),
            "m3_relative_determinant": fit_deg.get("m3_relative_determinant"),
        },
        "evaluation": (
            {
                "n_test": evaluation["n_test"],
                "mae_m0": evaluation["mae_m0"],
                "mae_m1": evaluation["mae_m1"],
                "mae_m2": evaluation["mae_m2"],
                "mae_m3": evaluation["mae_m3"],
                "improvement": evaluation["improvement"],
                "improvement_m2": evaluation["improvement_m2"],
                "improvement_m3": evaluation["improvement_m3"],
                "per_cell": evaluation["per_cell"],
            }
            if evaluation is not None
            else None
        ),
        "bootstrap": bootstrap,
        "evaluation_error": eval_error,
        "primary_disposition": disposition,
        "status_summary": status_summary,
        "relabel_sensitivity": relabel_sensitivity,
        "limitations": [
            "Across-cell width differences are confounded with cell "
            "effects by design; M1 is identified only from "
            "within-cell width variation, which is narrow for random "
            "3-SAT (see per-cell width_std).",
            "PySAT / CDCL responses are not in this analysis; the "
            "primary response is DPLL branch attempts only.",
            "The original C001-style completed-only regression and "
            "min-degree / incidence-width comparisons are not "
            "implemented here; they are separate secondary analyses.",
            "Elapsed time is never used as a predictor or a target.",
            "UNSAT rows in pilot / harness data carry no proof "
            "certificate; their verification status is "
            "UNSAT_SOLVER_AGREEMENT_ONLY unless a proof checker has "
            "certified them (Section 4.1).",
        ],
        "reproducibility": _reproducibility(population),
    }


